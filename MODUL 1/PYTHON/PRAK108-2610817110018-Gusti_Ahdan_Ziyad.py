laps = 5
distance = 14
PHI = 3.141592653589793
perimeter = distance / laps
radius = perimeter / (2 * PHI)

print("Diketahui:")
print(f"Pak Dengklek mengelilingi taman = {laps} Putaran")
print(f"Jarak tempuh Pak Dengklek = {distance} Kilometer")
print("Jawaban:")
print(f"Jari-jari taman yang dikelilingi Pak Dengklek adalah {radius:.2f} Kilometer")